# Downloads The Block List Project's adult domain list and writes it to the
# Android asset that ClearNet blocks at runtime (BundledBlocklist.kt). The
# domains are lower-cased, de-duplicated and sorted by byte value, because
# the app searches the file with binary search. Commit the result.

set -euo pipefail
export LC_ALL=C

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE_URL="https://blocklistproject.github.io/Lists/alt-version/porn-nl.txt"
OUTPUT="$PROJECT_ROOT/android/app/src/main/assets/blocklists/adult.txt"

download="$(mktemp)"
trap 'rm -f "$download"' EXIT
curl -fsSL "$SOURCE_URL" -o "$download"

mkdir -p "$(dirname "$OUTPUT")"
{
    echo "# Generated by scripts/update_adult_blocklist.sh from $SOURCE_URL"
    echo "# Licence: Unlicense (https://github.com/blocklistproject/Lists/blob/master/LICENSE)"
    echo "# Do not edit by hand: the app needs the domains sorted by byte value."
    echo "#"
    # The list's own header: title, homepage and last update
    grep '^#' "$download" || true
    grep -v '^#' "$download" |
        tr -d '\r[:blank:]' |
        tr '[:upper:]' '[:lower:]' |
        sed 's/\.$//' |
        grep -E '^[a-z0-9_-]+(\.[a-z0-9_-]+)+$' |
        sort -u
} > "$OUTPUT"

echo "Wrote $(grep -vc '^#' "$OUTPUT") domains to ${OUTPUT#"$PROJECT_ROOT"/}"
